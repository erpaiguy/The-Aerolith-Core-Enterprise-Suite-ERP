import type { CpmTiming } from './scenarios.js';
import type { Timing } from './stats.js';

export interface BenchResults {
  environment: {
    cpus: number;
    cpuModel: string;
    memoryGb: number;
    postgres: string;
    sharedBuffers: string;
    workMem: string;
    node: string;
    ranAt: string;
  };
  bigBoqItems: number;
  smallImportsMs: number[];
  importMs: number;
  importedRows: number;
  bytesFor1M: number;
  totalBoqBytes: number;
  firstWindow: Timing;
  scroll: Timing;
  collapsed: { timing: Timing; collapsedCount: number; maxQueries: number };
  search: Timing;
  sort: Timing;
  edit: Timing;
  insert: Timing;
  revisionMs: number;
  cpmFirst: CpmTiming;
  cpm: CpmTiming;
}

const ms = (v: number) => (v >= 10_000 ? `${(v / 1000).toFixed(1)} s` : `${Math.round(v)} ms`);
const mb = (b: number) => `${(b / 1024 ** 2).toFixed(0)} MB`;
const verdict = (measured: number, target: number) => (measured <= target ? 'PASS' : '**FAIL**');

export function renderReport(r: BenchResults): string {
  const e = r.environment;
  const rows: [string, string, number, number][] = [
    [
      'Open a 1M-line BOQ (header + first window, server side), p95',
      '< 1.5 s',
      r.firstWindow.p95,
      1500,
    ],
    ['Scroll: fetch a 200-row window at a random position, p95', '< 100 ms', r.scroll.p95, 100],
    ['Filter: description search (trigram), p95', '< 500 ms', r.search.p95, 500],
    ['Sort by amount (indexed), p95', '< 500 ms', r.sort.p95, 500],
    ['Edit a quantity + update all ancestor totals, p95', '< 300 ms', r.edit.p95, 300],
    ['Import 1M lines (stream + COPY + merge into indexed tables)', '< 5 min', r.importMs, 300_000],
    [
      'Full CPM recalculation, 50k activities (load + compute + write)',
      '< 3 s',
      r.cpm.totalMs,
      3000,
    ],
  ];
  const failures = rows.filter(([, , m, t]) => m > t).length;

  return `# Wave 0 Benchmark Results

Generated by \`tools/bench\` (\`pnpm --filter @aerolith/bench bench\`). Targets from [03-architecture.md §13](../03-architecture.md).

**Result: ${failures === 0 ? 'all targets met' : `${failures} target(s) missed`}.**

## Environment

| | |
|---|---|
| Machine | ${e.cpus} vCPU (${e.cpuModel}), ${e.memoryGb} GB RAM, cloud container |
| PostgreSQL | ${e.postgres}, default config: shared_buffers ${e.sharedBuffers}, work_mem ${e.workMem} |
| Node.js | ${e.node} |
| Run at | ${e.ranAt} |
| Data | 1 BOQ with ${r.bigBoqItems.toLocaleString('en-IN')} items (${r.importedRows.toLocaleString('en-IN')} rows incl. sections, 4 levels) + 4 BOQs of 200,000 items in the same tables + a 50,000-activity schedule |

Times are measured from the Node.js client, so they include the database round trip on localhost but not network latency
to a hosted database or browser rendering.

## Targets

| Operation | Target | Measured | Verdict |
|-----------|--------|----------|---------|
${rows.map(([name, target, m, t]) => `| ${name} | ${target} | ${ms(m)} | ${verdict(m, t)} |`).join('\n')}

## Detail

| Scenario | Runs | First | p50 | p95 | Max |
|----------|------|-------|-----|-----|-----|
${(
  [
    ['Open first window', r.firstWindow],
    ['Scroll window', r.scroll],
    [
      `Window with ${r.collapsed.collapsedCount} collapsed sections (up to ${r.collapsed.maxQueries} queries per window)`,
      r.collapsed.timing,
    ],
    ['Description search', r.search],
    ['Sort by amount', r.sort],
    ['Edit quantity + ancestor totals', r.edit],
    ['Insert a row between two rows (no renumbering)', r.insert],
  ] as [string, Timing][]
)
  .map(
    ([n, t]) =>
      `| ${n} | ${t.runs} | ${ms(t.first)} | ${ms(t.p50)} | ${ms(t.p95)} | ${ms(t.max)} |`,
  )
  .join('\n')}

| One-off operation | Time |
|-------------------|------|
| Import 1M-line BOQ | ${ms(r.importMs)} |
| Import 200k-line BOQs | ${r.smallImportsMs.map(ms).join(', ')} |
| Copy the 1M-line BOQ as a new revision | ${ms(r.revisionMs)} |
| CPM first run (cold): load / compute / write | ${ms(r.cpmFirst.loadMs)} / ${ms(r.cpmFirst.computeMs)} / ${ms(r.cpmFirst.writeMs)} |
| CPM second run: load / compute / write | ${ms(r.cpm.loadMs)} / ${ms(r.cpm.computeMs)} / ${ms(r.cpm.writeMs)} |
| Schedule size | ${r.cpm.activities.toLocaleString('en-IN')} activities, ${r.cpm.relations.toLocaleString('en-IN')} relations, finish day ${r.cpm.projectFinish} |

## Storage

| | Size |
|---|---|
| One 1M-line BOQ (rows + text + indexes) | ${mb(r.bytesFor1M)} |
| All BOQ tables after the run (before the revision copy) | ${mb(r.totalBoqBytes)} |

## Caveats

- A cloud container with fast local disk and no network hop to the database is the best case. A hosted Supabase project adds round-trip latency per query (typically tens of milliseconds from India to Mumbai) and has far less CPU and memory on small plans. Rerun this benchmark against a real Supabase project before trusting the numbers for the free tier.
- The import time excludes parsing an Excel file. Spreadsheet parsing is CPU-bound in Node.js and needs its own measurement when the importer exists.
- CPM uses working-day integers; real calendars (holidays, shifts) add cost to the compute step.
- Browser rendering time is not included. The 200-row window is what the canvas grid paints; that is a client-side budget.
`;
}
